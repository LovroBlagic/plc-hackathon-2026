"""Generate work/src/Team_Prices.st (price lists = 'cjenici', allowed by spec 4.1/5) from work/data CSVs.
PriceTT: Elektra two-tariff, constant per calendar quarter and VT/NT -> 2x4 table.
PriceDA: day-ahead, 35040 x REAL (run-length encoded with the IEC n(value) repeat syntax).
"""
import csv, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "work", "data")
def rd(name):
    return [r[1] for r in list(csv.reader(open(os.path.join(D, name))))[1:]]
tt = [float(x) for x in rd("PriceTT.csv")]
vt = [x.upper() == "TRUE" for x in rd("VT.csv")]
da = rd("PriceDA.csv")
assert len(tt) == len(vt) == len(da) == 35040
cum = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334, 365]
qstart = [0, 90, 181, 273]
nt, vh = {}, {}
for k in range(35040):
    q = max(i for i in range(4) if k // 96 >= qstart[i]) + 1
    (vh if vt[k] else nt).setdefault(q, set()).add(tt[k])
assert all(len(s) == 1 for s in list(nt.values()) + list(vh.values())), (nt, vh)
NT = [nt[q].pop() for q in range(1, 5)]
VT = [vh[q].pop() for q in range(1, 5)]
# run-length encode DA (keep the CSV text exactly so REAL rounding equals the simulator's literals)
runs = []
for v in da:
    if runs and runs[-1][1] == v:
        runs[-1][0] += 1
    else:
        runs.append([1, v])
items = [("%d(%s)" % (n, v)) if n > 1 else v for n, v in runs]
lines = []
for i in range(0, len(items), 12):
    lines.append("\t\t" + ", ".join(items[i:i + 12]))
out = []
out.append("// Team_Prices: price lists (cjenici, spec 3.9/4.1) generated by tools/gen_prices.py from the organizer CSVs.")
out.append("// Energy price only; grid fee and peak price come from SimParam. Not a simulator profile (FNE/FEC/EV are never embedded).")
out.append("VAR_GLOBAL CONSTANT")
out.append("\t// Elektra two-tariff energy price [EUR/kWh] per calendar quarter (1 = Jan-Mar ... 4 = Oct-Dec)")
out.append("\tTT_NT : ARRAY[1..4] OF REAL := [%s];" % ", ".join(repr(x) for x in NT))
out.append("\tTT_VT : ARRAY[1..4] OF REAL := [%s];" % ", ".join(repr(x) for x in VT))
out.append("END_VAR")
out.append("VAR_GLOBAL")
out.append("\t// Day-ahead energy price [EUR/kWh] per 15-min interval k = 0..35039 (ENTSO-E HR 2025, may be negative)")
out.append("\taDA : ARRAY[0..35039] OF REAL := [")
out.append(",\n".join(lines))
out.append("\t];")
out.append("END_VAR")
open(os.path.join(ROOT, "work", "src", "Team_Prices.st"), "w", newline="\n").write("\n".join(out) + "\n")
print("NT", NT, "VT", VT, "DA runs", len(runs))
